"""Draws ModMenuBE's pixel-art icons.

    python tools/make_icons.py

writes
    assets/icon.png                  the mod's logo (256 px; LeviMC Mods, launchers, ModMenuBE's own list)
    android/src/ButtonIcons.inc      the in-game MOD button as a PNG byte array

The button follows the look of Minecraft's touch HUD buttons (black chamfered outline, grey face with a
lighter top edge, black glyph); the art itself is drawn here.
"""

from pathlib import Path
import io

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent

# Logo palette: wood browns.
TILE = (107, 74, 46, 255)
TILE_DARK = (62, 42, 25, 255)
TILE_LIGHT = (138, 100, 64, 255)
PIECE = (201, 162, 106, 255)
PIECE_LIGHT = (226, 196, 142, 255)
PIECE_DARK = (138, 106, 62, 255)
OUTLINE = (46, 30, 17, 255)

# A puzzle piece: a 9x9 body, tabs on the top and the right, a notch on the left.
PIECE_12 = [
    "..TTTTT.....",
    "..TTTTT.....",
    "...TTT......",
    "TTTTTTTTT...",
    "TTTTTTTTT.TT",
    ".TTTTTTTTTTT",
    "..TTTTTTTTTT",
    ".TTTTTTTTTTT",
    "TTTTTTTTT.TT",
    "TTTTTTTTT...",
    "TTTTTTTTT...",
    "TTTTTTTTT...",
]

# The same piece as a solid glyph for the HUD button (10x10): an outline reads as a hand at this size.
GLYPH_10 = [
    "..KKKK....",
    "..KKKK....",
    "...KK.....",
    "KKKKKKKK..",
    "KKKKKKKK.K",
    ".KKKKKKKKK",
    ".KKKKKKKKK",
    "KKKKKKKK.K",
    "KKKKKKKK..",
    "KKKKKKKK..",
]


def logo() -> Image.Image:
    n = 16
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    p = img.load()
    # Tile with a chamfered corner, lit from the top left.
    for y in range(n):
        for x in range(n):
            corner = (x in (0, n - 1)) and (y in (0, n - 1))
            if corner:
                continue
            if y == 0 or x == 0:
                p[x, y] = TILE_LIGHT
            elif y == n - 1 or x == n - 1:
                p[x, y] = TILE_DARK
            else:
                p[x, y] = TILE
    ox, oy = 2, 2
    mask = {(x, y) for y, row in enumerate(PIECE_12) for x, c in enumerate(row) if c == "T"}
    for (x, y) in mask:
        up, left = (x, y - 1) in mask, (x - 1, y) in mask
        down, right = (x, y + 1) in mask, (x + 1, y) in mask
        if not down or not right:
            col = PIECE_DARK
        elif not up or not left:
            col = PIECE_LIGHT
        else:
            col = PIECE
        p[ox + x, oy + y] = col
    # A one-pixel outline around the piece, inside the tile.
    for y in range(-1, 13):
        for x in range(-1, 13):
            if (x, y) in mask:
                continue
            if any((x + dx, y + dy) in mask for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                tx, ty = ox + x, oy + y
                if 0 < tx < n - 1 and 0 < ty < n - 1:
                    p[tx, ty] = OUTLINE
    return img


def button(pressed: bool) -> Image.Image:
    n = 16
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    p = img.load()
    face = (88, 88, 88, 215) if pressed else (122, 122, 122, 215)
    top = (110, 110, 110, 230) if pressed else (160, 160, 160, 235)
    bottom = (60, 60, 60, 230) if pressed else (82, 82, 82, 235)
    edge = (12, 12, 12, 255)
    for y in range(n):
        for x in range(n):
            corner = (x in (0, n - 1)) and (y in (0, n - 1))
            if corner:
                continue
            if x in (0, n - 1) or y in (0, n - 1):
                p[x, y] = edge
            elif y == 1:
                p[x, y] = top
            elif y == n - 2:
                p[x, y] = bottom
            else:
                p[x, y] = face
    oy = 4 if pressed else 3  # the glyph sinks a pixel while pressed
    for y, row in enumerate(GLYPH_10):
        for x, c in enumerate(row):
            if c == "K":
                p[3 + x, oy + y] = edge
    return img


def scaled(img: Image.Image, size: int) -> Image.Image:
    return img.resize((size, size), Image.NEAREST)


def png_bytes(img: Image.Image) -> bytes:
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return buf.getvalue()


def c_array(name: str, data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    return f"inline constexpr unsigned char {name}[] = {{\n" + "\n".join(lines) + "\n};\n"


def main() -> None:
    (ROOT / "assets").mkdir(exist_ok=True)
    scaled(logo(), 256).save(ROOT / "assets" / "icon.png", optimize=True)
    # 128 px so the launcher's ImageView only ever scales down (nearest pixels stay sharp enough).
    # LeviLauncher has no pressed icon for floating buttons, so only the normal one is embedded.
    normal = png_bytes(scaled(button(False), 128))
    header = "// Generated by tools/make_icons.py. Do not edit.\n#pragma once\n\n" + c_array("kButtonIconPng", normal)
    (ROOT / "android" / "src" / "ButtonIcons.inc").write_text(header, encoding="utf-8", newline="\n")
    print("wrote assets/icon.png and android/src/ButtonIcons.inc")


if __name__ == "__main__":
    main()
